/**
 * The Playwright specs `guren browser:map` keeps under `tests/browser/generated/` once
 * `guren add browser-tests` has run (RFC 0033 §6), and the browser account seeder, pure: from the
 * feature map to source text. Specs carry no bracketed acceptance id, so neither `plan:verify` nor
 * `check --docs` reads one as a test of a plan behaviour (§8).
 */

