export const AXE_PACKAGE = '@axe-core/playwright'
/** RFC 0033 §12.2: conformance criteria only; `best-practice` rules are advice, and most of what axe reports on an existing app. */
export const A11Y_TAGS = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'] as const
/** Every accessibility test's title starts with it; the browser measurement splits its sets on it. */
export const A11Y_TITLE_PREFIX = 'a11y '
export const BROWSER_SEEDER_FILE = 'db/seeders/browser-account.ts'
/** Restated in the support template's `BROWSER_ACCOUNT_EMAIL`; a test pins the two together. */
export const BROWSER_ACCOUNT_EMAIL = 'browser@example.test'

export const GENERATED_HEADER = '// Generated by `guren browser:map` from the browser map; a run rewrites this file.\n'

export interface SpecOptions {
  /** The setup project signs in, so a route requiring a user can be visited. */
  signIn: boolean
  /** Write the accessibility spec; `browser:map` decides this from the app's install, `add browser-tests` before it installs. */
  accessibility?: boolean
}

interface SpecCase {
  title: string
  /** Absent for a `test.fixme`, whose title says why. */
  body?: string[]
  signedIn?: boolean
  testInfo?: boolean
}

const fixme = (title: string): SpecCase => ({ title })

/** A page a spec can open, or why it cannot: the one rule the smoke, view and accessibility specs share. */
type Target = { title: string; route: BrowserMapRoute; pages: readonly string[] } | { fixme: string }

function describeRoute(route: Pick<BrowserMapRoute, 'method' | 'path'>): string {
  return `${route.method} ${route.path}`
}

function componentAssertion(pages: readonly string[]): string {
  return pages.length === 1
    ? `expect(await initialComponent(page)).toBe(${quoteString(pages[0]!)})`
    : `expect([${pages.map(quoteString).join(', ')}]).toContain(await initialComponent(page))`
}

const NO_SIGN_IN = 'needs a signed-in user, and the app has no password sign-in for the setup project'

/** A route requiring a user, in an app the setup project cannot sign in to, is never visited as a guest. */
function visit(route: BrowserMapRoute, title: string, options: SpecOptions, body: string[]): SpecCase {
  if (route.authentication === 'required' && !options.signIn) return fixme(`${title}: ${NO_SIGN_IN}`)
  return { title, body, signedIn: route.authentication === 'required' }
}

function renderCases(cases: readonly SpecCase[], indent: string): string {
  return cases.map((entry) => entry.body
    ? [`${indent}test(${quoteString(entry.title)}, async ({ page }${entry.testInfo ? ', testInfo' : ''}) => {`, ...entry.body.map((line) => `${indent}  ${line}`), `${indent}})`].join('\n')
    : `${indent}test.fixme(${quoteString(entry.title)}, () => {})`).join('\n\n')
}

interface SpecPrelude {
  /** What the cases call besides the support helpers, imported only when a case runs. */
  imports: string[]
  playwrightTypes: string[]
  source: string
}

/** `supportImport` is the path from the spec's directory to tests/browser/support. */
function spec(cases: readonly SpecCase[], supportImport: string, prelude?: SpecPrelude): string {
  const guest = cases.filter((entry) => !entry.signedIn)
  const signedIn = cases.filter((entry) => entry.signedIn)
  const live = cases.some((entry) => entry.body)
  const support = [...(signedIn.length > 0 ? ['AUTH_FILE'] : []), ...(live ? ['initialComponent'] : [])]
  const types = live && prelude ? prelude.playwrightTypes.map((name) => `type ${name}`) : []
  const imports = [
    `import { ${[...(live ? ['expect', 'test'] : ['test']), ...types].join(', ')} } from '@playwright/test'`,
    ...(live && prelude ? prelude.imports : []),
    ...(support.length > 0 ? [`import { ${support.join(', ')} } from '${supportImport}'`] : []),
  ]
  const blocks = [
    ...(live && prelude ? [prelude.source] : []),
    ...(guest.length > 0 ? [renderCases(guest, '')] : []),
    ...(signedIn.length > 0 ? [`test.describe('signed in', () => {\n  test.use({ storageState: AUTH_FILE })\n\n${renderCases(signedIn, '  ')}\n})`] : []),
  ]
  return `${GENERATED_HEADER}${imports.join('\n')}\n\n${blocks.join('\n\n')}\n`
}

function landmarkTarget(feature: BrowserMap['features'][number]): Target {
  const { landmark } = feature
  if (!landmark) return { fixme: `${feature.name}: every route rendering it takes a path parameter` }
  return { title: `${feature.name}: ${describeRoute(landmark)} renders ${landmark.pages.join(' or ')}`, route: landmark, pages: landmark.pages }
}

/** One test per mapped landmark: it answers 200 with the page the graph says it renders, as `browser:doctor` checks. */
export function buildSmokeSpec(map: BrowserMap, options: SpecOptions): string {
  const cases = map.features.map((feature): SpecCase => {
    const target = landmarkTarget(feature)
    if ('fixme' in target) return fixme(target.fixme)
    return visit(target.route, target.title, options, [
      `const response = await page.goto(${quoteString(target.route.path)})`,
      'expect(response?.status()).toBe(200)',
      componentAssertion(target.pages),
    ])
  })
  return spec(cases.length > 0 ? cases : [fixme('the browser map has no feature to check yet')], '../support')
}

/** A label or name the page may also hold hidden (a collapsed menu, a second form) still passes on its visible copy. */
function visibleLocator(locator: string): string {
  return `await expect(${locator}.filter({ visible: true }).first()).toBeVisible()`
}

function locatorLines(entry: BrowserMapView): string[] {
  const fields = (entry.view.form?.fields ?? [])
    .filter((field) => field.input !== 'hidden')
    .map((field) => visibleLocator(`page.getByLabel(${quoteString(field.label)}, { exact: true })`))
  const actions = entry.view.actions.map(({ label }) => {
    const name = `{ name: ${quoteString(label)}, exact: true }`
    // The plan names an action, not its element: either a button or a link satisfies it.
    return visibleLocator(`page.getByRole('button', ${name}).or(page.getByRole('link', ${name}))`)
  })
  return [...fields, ...actions]
}

function viewTarget(entry: BrowserMapView): Target {
  const { view, routes } = entry
  const title = `view ${view.id} (${view.page})`
  const route = routes.find((candidate) => isParameterless(candidate.path))
  if (routes.length === 0) return { fixme: `${title}: no GET route renders it yet` }
  if (!route) return { fixme: `${title}: ${describeRoute(routes[0]!)} takes a path parameter; open a record to check it` }
  return { title: `${title} on ${describeRoute(route)}`, route, pages: [view.page] }
}

function viewCase(entry: BrowserMapView, options: SpecOptions): SpecCase {
  const target = viewTarget(entry)
  if ('fixme' in target) return fixme(target.fixme)
  return visit(target.route, target.title, options, [
    `await page.goto(${quoteString(target.route.path)})`,
    componentAssertion(target.pages),
    ...locatorLines(entry),
  ])
}

/** The views the plan specs check: every approved plan's, placed or not, but a dropped one. */
function plannedViews(map: BrowserMap): BrowserMapView[] {
  return [...map.features.flatMap((feature) => feature.views), ...map.unplacedViews].filter((entry) => entry.view.change.kind !== 'drop')
}

/**
 * One spec per approved plan with views: each view's form labels and action names, found on the page
 * that renders it. `sharedSlugs` is `PlanDiscovery.sharedSlugs` with app-relative files; a plan whose
 * slug another plan shares, approved or not, refuses, since its spec is named by that slug.
 */
export function buildPlanSpecs(map: BrowserMap, options: SpecOptions, sharedSlugs: ReadonlyMap<string, readonly string[]>): ScaffoldFileEntry[] {
  const views = plannedViews(map)
  const byPlan = new Map<string, BrowserMapView[]>()
  for (const entry of views) {
    const list = byPlan.get(entry.plan)
    if (list) list.push(entry)
    else byPlan.set(entry.plan, [entry])
  }
  return [...byPlan.keys()].sort(compareStrings).map((plan) => {
    const slug = planSlug(plan)
    const shared = sharedSlugs.get(slug)
    if (shared) throw new CliError(`${shared.join(', ')} share the slug ${slug}, so ${plan}'s browser spec would be named for more than one plan; rename all but one (guren check --plan reports this too).`)
    const cases = [...byPlan.get(plan)!].sort((a, b) => compareStrings(a.view.id, b.view.id)).map((entry) => viewCase(entry, options))
    return { path: `${GENERATED_SPECS_DIR}/plans/${slug}.browser.ts`, contents: spec(cases, '../../support') }
  })
}

const A11Y_PRELUDE: SpecPrelude = {
  imports: [`import { AxeBuilder } from '${AXE_PACKAGE}'`, "import { a11y } from '../a11y'"],
  playwrightTypes: ['Page', 'TestInfo'],
  source: `const TAGS = [${A11Y_TAGS.map(quoteString).join(', ')}]

/** Fails on any violation of the WCAG A and AA rules; what axe could not decide is attached, never failed. */
async function checkAccessibility(page: Page, testInfo: TestInfo): Promise<void> {
  // A client-rendered page fills #app after load; axe on an empty root would pass a page it never read.
  await expect(page.locator('#app > *').first()).toBeAttached()
  await page.waitForLoadState('networkidle')
  let builder = new AxeBuilder({ page }).withTags(TAGS)
  if (a11y.disableRules.length > 0) builder = builder.disableRules(a11y.disableRules)
  for (const selector of a11y.exclude) builder = builder.exclude(selector)
  const results = await builder.analyze()
  await testInfo.attach('axe-results.json', {
    contentType: 'application/json',
    body: JSON.stringify({ tags: TAGS, disabledRules: a11y.disableRules, excluded: a11y.exclude, violations: results.violations, incomplete: results.incomplete }, null, 2),
  })
  const violations = results.violations.map((violation) =>
    \`\${violation.id} (\${violation.impact ?? 'unknown'}): \${violation.help} \${violation.helpUrl} at \${violation.nodes.slice(0, 3).map((node) => node.target.join(' ')).join(', ')}\`)
  expect(violations, \`axe: \${results.violations.map((violation) => violation.id).join(', ')}\`).toEqual([])
}`,
}

/**
 * One test per landmark and per plan view the other specs open (RFC 0033 §12.2), each visit once:
 * a view on a landmark's route is not checked twice. A page another spec cannot open is a fixme here too,
 * once per title, since every plan's views share this file and Playwright refuses a duplicate title.
 */
export function buildA11ySpec(map: BrowserMap, options: SpecOptions): string {
  const targets = [...map.features.map(landmarkTarget), ...plannedViews(map).sort((a, b) => compareStrings(a.plan, b.plan) || compareStrings(a.view.id, b.view.id)).map(viewTarget)]
  const visited = new Set<string>()
  const titles = new Set<string>()
  const cases: SpecCase[] = []
  for (const target of targets) {
    if ('fixme' in target) {
      const title = `${A11Y_TITLE_PREFIX}${target.fixme}`
      if (!titles.has(title)) cases.push(fixme(title))
      titles.add(title)
      continue
    }
    const key = describeRoute(target.route)
    if (visited.has(key)) continue
    visited.add(key)
    const entry = visit(target.route, `${A11Y_TITLE_PREFIX}${target.title}`, options, [
      `await page.goto(${quoteString(target.route.path)})`,
      componentAssertion(target.pages),
      'await checkAccessibility(page, testInfo)',
    ])
    cases.push(entry.body ? { ...entry, testInfo: true } : entry)
  }
  return spec(cases.length > 0 ? cases : [fixme(`${A11Y_TITLE_PREFIX}the browser map has no feature to check yet`)], '../support', A11Y_PRELUDE)
}

export interface BrowserSeederColumns {
  name: boolean
  emailVerifiedAt: boolean
}

/** The browser account, guarded: it writes only for the app `guren browser:serve` starts, never in production. */
export function buildBrowserSeeder(dialect: SchemaDialect, columns: BrowserSeederColumns): string {
  const context = seederContextTypes[dialect]
  const values = [
    ...(columns.name ? ["name: 'Browser Tests'"] : []),
    `email: ${quoteString(BROWSER_ACCOUNT_EMAIL)}`,
    'passwordHash',
    ...(columns.emailVerifiedAt ? ['emailVerifiedAt: verifiedAt'] : []),
  ]
  const set = `{ passwordHash${columns.emailVerifiedAt ? ', emailVerifiedAt: verifiedAt' : ''} }`
  const upsert = dialect === 'mysql'
    ? `.onDuplicateKeyUpdate({ set: ${set} })`
    : `.onConflictDoUpdate({ target: users.email, set: ${set} })`
  return `import { defineSeeder, Hash, type ${context} } from '@guren/core'
import { users } from '../schema.js'

// Boot-time seeding and \`db:seed --force\` reach this file in every run, so the guard is here:
// only \`guren browser:serve\` sets GUREN_BROWSER_SEED, for the app it starts.
export default defineSeeder(async ({ db }: ${context}) => {
  if (process.env.GUREN_BROWSER_SEED !== '1' || process.env.NODE_ENV === 'production') return
  const password = process.env.BROWSER_TEST_PASSWORD
  if (!password) {
    console.warn('BROWSER_TEST_PASSWORD is unset, so the browser account was not seeded.')
    return
  }
  const passwordHash = await new Hash().hash(password)${columns.emailVerifiedAt ? '\n  const verifiedAt = new Date()' : ''}
  await db
    .insert(users)
    .values({ ${values.join(', ')} })
    ${upsert}
})
`
}
