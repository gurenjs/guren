/**
 * The Playwright specs and the browser account seeder `guren add browser-tests` writes (RFC 0033 §6),
 * pure: from the feature map to source text. Specs carry no bracketed acceptance id, so neither
 * `plan:verify` nor `check --docs` reads one as a test of a plan behaviour (§8).
 */

import type { BrowserMap, BrowserMapRoute } from './browser-map'
import { compareStrings } from './spec-artifact'
import type { PlanView } from './plan/schema'
import { planSlug } from './plan/state'
import { seederContextTypes, type SchemaDialect } from './patch-helpers'
import { quoteString } from './schema-columns'

export const GENERATED_SPECS_DIR = 'tests/browser/generated'
export const SMOKE_SPEC_FILE = `${GENERATED_SPECS_DIR}/smoke.browser.ts`
export const BROWSER_SEEDER_FILE = 'db/seeders/browser-account.ts'
/** Restated in the support template's `BROWSER_ACCOUNT_EMAIL`, which signs in with it. */
export const BROWSER_ACCOUNT_EMAIL = 'browser@example.test'

export const GENERATED_HEADER = '// Generated by `guren add browser-tests` from the browser map; a re-run rewrites this file.\n'

export interface SpecOptions {
  /** The setup project signs in, so a route requiring a user can be visited. */
  signIn: boolean
}

export interface GeneratedSpec {
  /** App-relative, POSIX. */
  path: string
  contents: string
}

interface SpecCase {
  title: string
  /** `undefined` writes a `test.fixme`, its title saying why. */
  body?: string[]
  signedIn: boolean
}

function describeRoute(route: Pick<BrowserMapRoute, 'method' | 'path'>): string {
  return `${route.method} ${route.path}`
}

function componentAssertion(pages: readonly string[]): string {
  return pages.length === 1
    ? `expect(await initialComponent(page)).toBe(${quoteString(pages[0]!)})`
    : `expect([${pages.map(quoteString).join(', ')}]).toContain(await initialComponent(page))`
}

/** A route requiring a user, in an app the setup project cannot sign in to, is never visited as a guest. */
function needsUnavailableSignIn(route: BrowserMapRoute, options: SpecOptions): boolean {
  return route.authentication === 'required' && !options.signIn
}

const NO_SIGN_IN = 'needs a signed-in user, and the app has no password sign-in for the setup project'

function renderCase(entry: SpecCase, indent: string): string[] {
  if (!entry.body) return [`${indent}test.fixme(${quoteString(entry.title)}, () => {})`]
  return [
    `${indent}test(${quoteString(entry.title)}, async ({ page }) => {`,
    ...entry.body.map((line) => `${indent}  ${line}`),
    `${indent}})`,
  ]
}

/** `supportImport` is the path from the spec's directory to tests/browser/support. */
function spec(mapped: readonly SpecCase[], supportImport: string): string {
  const cases = mapped.length > 0 ? mapped : [{ title: 'the browser map has no feature to check yet', signedIn: false }]
  const live = cases.filter((entry) => entry.body)
  const guest = cases.filter((entry) => !entry.signedIn)
  const signedIn = cases.filter((entry) => entry.signedIn)
  const support = [...(signedIn.length > 0 ? ['AUTH_FILE'] : []), ...(live.length > 0 ? ['initialComponent'] : [])]
  const lines = [
    GENERATED_HEADER.trimEnd(),
    `import { ${live.length > 0 ? 'expect, test' : 'test'} } from '@playwright/test'`,
    ...(support.length > 0 ? [`import { ${support.join(', ')} } from '${supportImport}'`] : []),
    '',
    ...guest.flatMap((entry) => [...renderCase(entry, ''), '']),
  ]
  if (signedIn.length > 0) {
    lines.push("test.describe('signed in', () => {", '  test.use({ storageState: AUTH_FILE })', '')
    signedIn.forEach((entry, index) => lines.push(...renderCase(entry, '  '), ...(index < signedIn.length - 1 ? [''] : [])))
    lines.push('})', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

/** One test per mapped landmark: it answers 200 with the page the graph says it renders, as `browser:doctor` checks. */
export function buildSmokeSpec(map: BrowserMap, options: SpecOptions): string {
  const cases: SpecCase[] = map.features.map((feature): SpecCase => {
    const { landmark } = feature
    if (!landmark) return { title: `${feature.name}: every route rendering it takes a path parameter`, signedIn: false }
    const title = `${feature.name}: ${describeRoute(landmark)} renders ${landmark.pages.join(' or ')}`
    if (needsUnavailableSignIn(landmark, options)) return { title: `${title} ${NO_SIGN_IN}`, signedIn: false }
    return {
      title,
      signedIn: landmark.authentication === 'required',
      body: [
        `const response = await page.goto(${quoteString(landmark.path)})`,
        'expect(response?.status()).toBe(200)',
        componentAssertion(landmark.pages),
      ],
    }
  })
  return spec(cases, '../support')
}

function hasPathParameter(path: string): boolean {
  return /[:*]/u.test(path)
}

/** Every GET route the map holds once, whatever feature it joined. */
function getRoutes(map: BrowserMap): BrowserMapRoute[] {
  const routes = new Map<string, BrowserMapRoute>()
  for (const route of map.features.flatMap((feature) => feature.routes)) {
    if (route.method === 'GET') routes.set(describeRoute(route), route)
  }
  return [...routes.values()].sort((a, b) => compareStrings(a.path, b.path))
}

function locatorLines(view: PlanView): string[] {
  const fields = (view.form?.fields ?? [])
    .filter((field) => field.input !== 'hidden')
    .map((field) => `await expect(page.getByLabel(${quoteString(field.label)}, { exact: true })).toBeVisible()`)
  const actions = view.actions.map(({ label }) => {
    const name = `{ name: ${quoteString(label)}, exact: true }`
    // The plan names an action, not its element: either a button or a link satisfies it.
    return `await expect(page.getByRole('button', ${name}).or(page.getByRole('link', ${name})).first()).toBeVisible()`
  })
  return [...fields, ...actions]
}

function viewCase(view: PlanView, routes: readonly BrowserMapRoute[], options: SpecOptions): SpecCase {
  const rendering = routes.filter((route) => route.pages.includes(view.page))
  const route = rendering.find((entry) => !hasPathParameter(entry.path))
  const title = `view ${view.id} (${view.page})`
  if (rendering.length === 0) return { title: `${title}: no GET route renders it yet`, signedIn: false }
  if (!route) return { title: `${title}: ${describeRoute(rendering[0]!)} takes a path parameter; open a record to check it`, signedIn: false }
  if (needsUnavailableSignIn(route, options)) return { title: `${title}: ${describeRoute(route)} ${NO_SIGN_IN}`, signedIn: false }
  return {
    title: `${title} on ${describeRoute(route)}`,
    signedIn: route.authentication === 'required',
    body: [`await page.goto(${quoteString(route.path)})`, componentAssertion([view.page]), ...locatorLines(view)],
  }
}

/** One spec per approved plan with views: each view's form labels and action names, found on the page that renders it. */
export function buildPlanSpecs(map: BrowserMap, options: SpecOptions): GeneratedSpec[] {
  const byPlan = new Map<string, PlanView[]>()
  for (const { plan, view } of map.features.flatMap((feature) => feature.views)) {
    if (view.change.kind === 'drop') continue
    byPlan.set(plan, [...(byPlan.get(plan) ?? []), view])
  }
  const routes = getRoutes(map)
  return [...byPlan]
    .sort(([a], [b]) => compareStrings(a, b))
    .map(([plan, views]) => ({
      path: `${GENERATED_SPECS_DIR}/plans/${planSlug(plan)}.browser.ts`,
      contents: spec([...views].sort((a, b) => compareStrings(a.id, b.id)).map((view) => viewCase(view, routes, options)), '../../support'),
    }))
}

export interface BrowserSeederColumns {
  name: boolean
  emailVerifiedAt: boolean
}

/** The browser account, guarded: it writes only for the app `guren browser:serve` starts, never in production. */
export function buildBrowserSeeder(dialect: SchemaDialect, columns: BrowserSeederColumns): string {
  const context = seederContextTypes[dialect]
  const values = [
    ...(columns.name ? ["name: 'Browser Tests'"] : []),
    `email: ${quoteString(BROWSER_ACCOUNT_EMAIL)}`,
    'passwordHash',
    ...(columns.emailVerifiedAt ? ['emailVerifiedAt: new Date()'] : []),
  ]
  const upsert = dialect === 'mysql'
    ? '.onDuplicateKeyUpdate({ set: { passwordHash } })'
    : '.onConflictDoUpdate({ target: users.email, set: { passwordHash } })'
  return `import { defineSeeder, Hash, type ${context} } from '@guren/core'
import { users } from '../schema.js'

// Boot-time seeding and \`db:seed --force\` reach this file in every run, so the guard is here:
// only \`guren browser:serve\` sets GUREN_BROWSER_SEED, for the app it starts.
export default defineSeeder(async ({ db }: ${context}) => {
  if (process.env.GUREN_BROWSER_SEED !== '1' || process.env.NODE_ENV === 'production') return
  const password = process.env.BROWSER_TEST_PASSWORD
  if (!password) {
    console.warn('BROWSER_TEST_PASSWORD is unset in .env, so the browser account was not seeded.')
    return
  }
  const passwordHash = await new Hash().hash(password)
  await db
    .insert(users)
    .values({ ${values.join(', ')} })
    ${upsert}
})
`
}
