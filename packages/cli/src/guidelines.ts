import { resolve } from 'node:path'
import { consola } from 'consola'
import {
  discoverControllerFiles,
  discoverResourceFiles,
  discoverEventFiles,
  discoverJobFiles,
  discoverMiddlewareFiles,
  discoverValidatorFiles,
  classNameFromPath,
  fileExists,
  directoryExists,
  excludeBarrelFiles,
} from './discovery'
import { listModels } from './model-list'
import { writeFileSafe } from './utils'

export interface GuidelinesOptions {
  cwd?: string
  output?: string
}

export async function generateGuidelines(options: GuidelinesOptions = {}): Promise<string> {
  const cwd = resolve(options.cwd ?? process.cwd())
  const lines: string[] = []

  lines.push('# Project Guidelines (auto-generated)')
  lines.push('')
  lines.push('> Generated by `bunx guren guidelines`. Do not edit manually.')
  lines.push('')

  // Naming conventions
  lines.push('## Naming Conventions')
  const controllers = excludeBarrelFiles(await discoverControllerFiles(cwd)).map(classNameFromPath)
  if (controllers.length > 0) {
    const allSingular = controllers.every((c) => !c.endsWith('sController'))
    lines.push(`- Controllers: ${allSingular ? 'singular' : 'plural'} resource name (e.g., ${controllers[0]})`)
  }
  lines.push(`- Models: PascalCase, singular (e.g., Post, User)`)
  lines.push(`- Views: nested folders under resources/js/pages/ (e.g., Posts/Index.tsx)`)
  lines.push('')

  // Auth setup
  lines.push('## Authentication')
  const hasAuth = await directoryExists(resolve(cwd, 'app/Http/Controllers/Auth'))
  const models = await listModels({ appRoot: cwd })
  const authModel = models.find((m) => m.usesAuth)
  if (hasAuth && authModel) {
    lines.push(`- Auth is configured with ${authModel.className} model`)
    lines.push('- Session-based authentication (web guard)')
  } else if (hasAuth) {
    lines.push('- Auth controllers present but no AuthenticatableModel found')
  } else {
    lines.push('- No auth configured. Run: `bunx guren add auth`')
  }
  lines.push('')

  // Models & Relationships
  lines.push('## Models & Relationships')
  if (models.length > 0) {
    for (const model of models) {
      const rels = model.relationships.map((r) => {
        const target = r.relatedModel ? ` → ${r.relatedModel}` : ''
        return `${r.name} (${r.type}${target})`
      })
      const traits: string[] = []
      if (model.usesAuth) traits.push('Authenticatable')
      if (model.hasSoftDeletes) traits.push('SoftDeletes')
      const traitStr = traits.length > 0 ? ` [${traits.join(', ')}]` : ''

      lines.push(`- **${model.className}**${traitStr}: ${rels.length > 0 ? rels.join(', ') : 'no relationships'}`)
    }
  } else {
    lines.push('- No models found')
  }
  lines.push('')

  // Validation approach
  lines.push('## Validation')
  const validators = excludeBarrelFiles(await discoverValidatorFiles(cwd)).map(classNameFromPath)
  if (validators.length > 0) {
    lines.push(`- Centralized validators in app/Http/Validators/`)
    lines.push(`- Available: ${validators.join(', ')}`)
    lines.push('- Pattern: Zod schemas exported per resource')
  } else {
    lines.push('- No centralized validators found. Validation done inline in controllers.')
  }
  lines.push('')

  // Resources
  const resources = excludeBarrelFiles(await discoverResourceFiles(cwd)).map(classNameFromPath)
  if (resources.length > 0) {
    lines.push('## API Resources')
    lines.push(`- All API responses use JsonResource pattern`)
    lines.push(`- Available: ${resources.join(', ')}`)
    lines.push('')
  }

  // Events & Jobs
  const events = excludeBarrelFiles(await discoverEventFiles(cwd)).map(classNameFromPath)
  const jobs = excludeBarrelFiles(await discoverJobFiles(cwd)).map(classNameFromPath)
  const middleware = excludeBarrelFiles(await discoverMiddlewareFiles(cwd)).map(classNameFromPath)

  if (events.length > 0 || jobs.length > 0) {
    lines.push('## Events & Jobs')
    if (events.length > 0) lines.push(`- Events: ${events.join(', ')}`)
    if (jobs.length > 0) lines.push(`- Jobs: ${jobs.join(', ')}`)
    lines.push('')
  }

  if (middleware.length > 0) {
    lines.push('## Middleware')
    lines.push(`- Custom middleware: ${middleware.join(', ')}`)
    lines.push('')
  }

  // When creating new features
  lines.push('## When Creating New Features')
  lines.push('1. Create model in `app/Models/`')
  lines.push('2. Create controller in `app/Http/Controllers/`')
  lines.push('3. Create views in `resources/js/pages/{Feature}/`')
  lines.push('4. Create validator in `app/Http/Validators/`')
  lines.push('5. Create resource in `app/Http/Resources/`')
  lines.push('6. Register routes in `routes/web.ts`')
  lines.push('7. Run `bunx guren codegen` after adding routes')
  lines.push('')

  const output = lines.join('\n')

  if (options.output) {
    await writeFileSafe(resolve(cwd, options.output), output, { force: true })
    consola.success(`Guidelines written to ${options.output}`)
  }

  return output
}
